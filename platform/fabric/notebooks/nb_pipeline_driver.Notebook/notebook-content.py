# Install LakeLogic without %pip, which cancels Fabric job sessions.
# --upgrade: pip --target skips packages already present, so a reused container keeps old versions.
# A private target per run: parallel notebooks installing into one folder break each other.
import os, subprocess, sys, uuid
_TARGET = f"/tmp/lakelogic_libs_{os.getpid()}_{uuid.uuid4().hex[:8]}"
# [synthetic] brings Faker for realistic values; pdfplumber reads PDFs for document contracts.
# Capture pip's output: streaming its full log into the cell breaks the Fabric session
# (MismatchedInputException: No content to map). Warnings and errors are still printed.
_pip = subprocess.run([sys.executable, "-m", "pip", "install", "--upgrade", "--target",
                       _TARGET, "lakelogic[synthetic,documents] @ file:///lakehouse/default/Files/wheels/lakelogic-1.88.0-py3-none-any.whl", "pdfplumber", "typing_extensions",
                       "typing-inspection", "pyyaml"],
                      capture_output=True, text=True)
for _line in (_pip.stdout + _pip.stderr).splitlines():
    if "WARNING" in _line or "ERROR" in _line:
        print(_line)
if _pip.returncode != 0:
    print(_pip.stderr[-3000:])
    raise RuntimeError(f"pip install failed with exit code {_pip.returncode}: {_pip.stderr.strip()[-1500:]}")
if _TARGET not in sys.path:
    sys.path.insert(0, _TARGET)
for _m in list(sys.modules):
    if _m.split(".")[0] in ("lakelogic", "pydantic", "pydantic_core", "typing_extensions", "typing_inspection"):
        del sys.modules[_m]
# Print the installed LakeLogic version.
