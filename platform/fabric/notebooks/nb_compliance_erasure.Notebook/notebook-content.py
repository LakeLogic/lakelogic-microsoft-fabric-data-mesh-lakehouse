from lakelogic.core.evidence_tables import resolve_evidence_target, write_evidence_rows

# The ENGINE owns the evidence tables: their names (lakelogic/core/metadata_names —
# `lakelogic_erasure_evidence` / `lakelogic_retention_evidence` on Fabric, which is
# underscore-unsafe), their schema, and their place — in the DOMAIN schema, beside the run log
# this system's `_system.yaml` declares. Never a central `compliance` schema, and never the run
# log itself: Verify counts run-log rows as pipeline runs.
_run_log_table = str((getattr(registry, "metadata", None) or {}).get("run_log_table") or "")
if not _run_log_table or "{" in _run_log_table:
    _run_log_table = f"{registry.storage.domain_catalog}.lakelogic_run_log"
EVIDENCE_METADATA = {"run_log_table": _run_log_table, "run_log_backend": "spark", "platform": "fabric"}


def evidence_table(kind):
    target = resolve_evidence_target(kind, EVIDENCE_METADATA, engine_name="spark")
    return target[1] if target else None


def record_evidence(kind, rows):
    """Append engine-schema rows to the domain's evidence table. Raises when rows were not
    recorded — evidence that silently goes nowhere is worse than a failed run."""
    written_to = write_evidence_rows(kind, rows, EVIDENCE_METADATA, engine_name="spark")
    if rows and not written_to:
        raise Exception(f"{kind} was NOT recorded in {evidence_table(kind)} - see the warning above.")
    print(f"Recorded {len(rows) if written_to else 0} row(s) in {written_to or evidence_table(kind)}.")
    return written_to

