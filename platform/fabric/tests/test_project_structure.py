def _notebook_sources():
    # Keyed by the stem (`compliance_erasure.Notebook`), whatever the folder's display-name
    # prefix: `nb_` in the shared layout, `<prefix>_nb_` under an artifact prefix, none in a
    # legacy repo.
    out = {}
    for p in (ROOT / "notebooks").glob("*.Notebook/notebook-content.py"):
        name = re.sub(r"^(?:[a-z0-9]+_)?nb_", "", p.parent.name)
        out[name] = p.read_text(encoding="utf-8")
    return out


def test_no_notebook_creates_or_writes_a_central_compliance_schema():
    for name, src in _notebook_sources().items():
        assert not re.search(r"(?i)CREATE SCHEMA IF NOT EXISTS\s+`?compliance", src), name
        assert "compliance." not in src.replace("compliance_", ""), f"{name} writes to compliance.<table>"


def test_evidence_goes_to_the_engine_tables_beside_the_domain_run_log():
    for name in ("compliance_erasure.Notebook", "compliance_retention_check.Notebook"):
        src = _notebook_sources()[name]
        assert "write_evidence_rows" in src and "resolve_evidence_target" in src, name
        assert '"platform": "fabric"' in src, name
    for path in SYSTEM_FILES:
        meta = yaml.safe_load(path.read_text(encoding="utf-8"))["metadata"]
        assert meta["run_log_table"].startswith("{domain_catalog}."), path
        assert meta.get("platform") == "fabric", path


