#!/usr/bin/env python
"""Deploy this Medallion mesh project into Microsoft Fabric (customer-run).

Runs with YOUR Fabric credentials — LakeLogic never executes this script; it ships in
the export bundle and you run it. It drives the public Fabric REST API and the OneLake
DFS API directly, authenticating with tokens from the Azure CLI (`az account
get-access-token`), so no Fabric SDK is required. It:

  1. resolves (or creates) the target workspace + schema-enabled lakehouse
  2. uploads _contracts/ into the lakehouse OneLake Files under _contracts/
  3. imports each notebooks/<name>.Notebook/ item folder, attaching the lakehouse
  4. creates/updates each pipelines/<name>.DataPipeline/ item folder — the per-system
     pipelines, the _synthetic_seed synthetic-twin pipeline, and (multi-system) the
     mesh orchestrator

This bundle is in Fabric's GIT-INTEGRATION layout: an item is a FOLDER carrying its
source plus a .platform file, and pipelines reference notebooks by the target's
logicalId (from .platform) against a zero workspaceId. Fabric's git sync resolves those
on its own; the REST API does not, so this script does: it creates the items, then
rewrites each logicalId to the GUID it became. Pipelines are created in dependency
order, because a reference is only sendable once the item it names exists.

Prerequisites: `az login` as a Fabric workspace admin; `pip install pyyaml requests`.

Usage:
  python deploy.py --workspace <ws> --lakehouse <lh> [--capacity <guid>]
  python deploy.py ... --setup-only                 # provision + upload + import; no pipelines
  python deploy.py ... --domain marketplace/rideflow  # only that one system's pipeline
  python deploy.py ... --invoke-connection <guid>   # a connection for pipeline invokes

Provenance:
#   generated by: LakeLogic Medallion Builder
#   revision: chv1:b923be7ecb5204b7e732ee88e204f3b7e0ad4399baebddecbf7096861f7ef99e
#   governance seal: sha256:9e5ae31d73707a34beb59b7d2b5e37531f6a5cd8df34014615c54e3f7ffeb7db
#   source: estate snapshot snap-1f09b935d5194015
"""
from __future__ import annotations

import argparse
import base64
import json
import subprocess
import sys
import time
from pathlib import Path

import requests
import yaml

ROOT = Path(__file__).resolve().parent
FAB_API = "https://api.fabric.microsoft.com/v1"
ONELAKE = "https://onelake.dfs.fabric.microsoft.com"

for _s in (sys.stdout, sys.stderr):
    try:
        _s.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass


def _token(resource: str) -> str:
    out = subprocess.run(
        f"az account get-access-token --resource {resource} --query accessToken -o tsv",
        capture_output=True, text=True, shell=True,
    )
    if out.returncode != 0 or not out.stdout.strip():
        sys.exit(f"Could not get a token for {resource}. Run `az login` first.\n{out.stderr}")
    return out.stdout.strip()


def _hdr(tok, ct="application/json"):
    h = {"Authorization": f"Bearer {tok}"}
    if ct:
        h["Content-Type"] = ct
    return h


def _poll_lro(resp, tok):
    if resp.status_code not in (200, 201, 202):
        raise RuntimeError(f"{resp.status_code}: {resp.text[:500]}")
    if resp.status_code != 202:
        return resp.json() if resp.text else {}
    op = resp.headers.get("Location")
    while True:
        time.sleep(3)
        r = requests.get(op, headers=_hdr(tok))
        st = r.json().get("status")
        if st in ("Succeeded", "Completed"):
            res = requests.get(op + "/result", headers=_hdr(tok))
            return res.json() if res.text else {}
        if st in ("Failed", "Undefined"):
            raise RuntimeError(f"Operation failed: {r.text[:500]}")


def get_or_create_workspace(tok, name, capacity_id):
    r = requests.get(f"{FAB_API}/workspaces", headers=_hdr(tok))
    r.raise_for_status()
    for w in r.json().get("value", []):
        if w.get("displayName") == name:
            print(f"  workspace '{name}' exists ({w['id']})")
            return w["id"]
    if not capacity_id:
        sys.exit(f"Workspace '{name}' not found; pass --capacity <Fabric capacity GUID>.")
    r = requests.post(f"{FAB_API}/workspaces", headers=_hdr(tok),
                      json={"displayName": name, "capacityId": capacity_id})
    r.raise_for_status()
    wid = r.json()["id"]
    print(f"  created workspace '{name}' ({wid})")
    return wid


def get_or_create_lakehouse(tok, wid, name):
    r = requests.get(f"{FAB_API}/workspaces/{wid}/lakehouses", headers=_hdr(tok))
    r.raise_for_status()
    for lh in r.json().get("value", []):
        if lh.get("displayName") == name:
            lid = lh["id"]
            detail = requests.get(f"{FAB_API}/workspaces/{wid}/lakehouses/{lid}", headers=_hdr(tok))
            props = (detail.json() or {}).get("properties", {}) if detail.ok else {}
            if not props.get("defaultSchema"):
                sys.exit(f"Lakehouse '{name}' is not schema-enabled; recreate with schemas ON.")
            print(f"  lakehouse '{name}' exists ({lid})")
            return lid
    res = _poll_lro(requests.post(f"{FAB_API}/workspaces/{wid}/lakehouses", headers=_hdr(tok),
                                  json={"displayName": name,
                                        "creationPayload": {"enableSchemas": True}}), tok)
    lid = res.get("id")
    print(f"  created schema-enabled lakehouse '{name}' ({lid})")
    return lid


def upload_contracts(store_tok, workspace, lakehouse):
    """Upload _contracts/ into the lakehouse's OneLake Files via the DFS API.

    The destination folder is stamped in at render time and matches what the notebooks in
    this bundle read — under an artifact prefix both move together.
    """
    src = ROOT / "_contracts"
    base = f"{ONELAKE}/{workspace}/{lakehouse}.Lakehouse/Files/ll_contracts"
    n = 0
    for f in sorted(src.rglob("*")):
        if f.is_dir():
            continue
        rel = f.relative_to(src).as_posix()
        url = f"{base}/{rel}"
        data = f.read_bytes()
        requests.put(url + "?resource=file", headers=_hdr(store_tok, None)).raise_for_status()
        requests.patch(url + "?action=append&position=0",
                       headers={**_hdr(store_tok, None), "Content-Type": "application/octet-stream"},
                       data=data).raise_for_status()
        requests.patch(url + f"?action=flush&position={len(data)}",
                       headers=_hdr(store_tok, None)).raise_for_status()
        n += 1
    print(f"  uploaded {n} contract files into Files/ll_contracts")


ZERO_GUID = "00000000-0000-0000-0000-000000000000"


def _item_dir(parent):
    """The bundle directory holding ``parent`` items — ``notebooks`` or ``ll_notebooks``.

    Matched by SUFFIX because the directory carries this deploy's artifact prefix. An exact
    match found nothing at all in a prefixed bundle, and deployed an empty workspace.
    """
    exact = ROOT / parent
    if exact.is_dir():
        return exact
    for d in sorted(ROOT.iterdir()):
        if d.is_dir() and d.name.endswith(f"_{parent}"):
            return d
    return None


def _item_folders(parent, suffix, content_name):
    """The bundle's <name>{suffix}/ item folders:
    [(base, logicalId, content, platform, displayName), ...].

    The bundle is in Fabric's GIT-INTEGRATION layout — an item is a FOLDER carrying its
    source plus a .platform file, not a flat .ipynb/.json. Reading it any other way finds
    nothing at all and deploys an empty workspace.

    ``displayName`` (from `.platform`) is what the item is CALLED in the workspace —
    "[dev] payments / stripe — Full Pipeline Orchestrator". The base is a file stem, which
    has to stay stable because it mints the logicalId, so the two are not the same thing.
    """
    out = []
    root = _item_dir(parent)
    if root is None:
        return out
    for folder in sorted(root.iterdir()):
        if not folder.is_dir() or not folder.name.endswith(suffix):
            continue
        content = folder / content_name
        if not content.exists():
            continue
        platform = folder / ".platform"
        logical, display = "", ""
        if platform.exists():
            doc = json.loads(platform.read_text(encoding="utf-8"))
            logical = (doc.get("config") or {}).get("logicalId") or ""
            display = (doc.get("metadata") or {}).get("displayName") or ""
        out.append((folder.name[: -len(suffix)], logical,
                    content.read_bytes(),
                    platform.read_bytes() if platform.exists() else None,
                    display))
    return out


def ensure_folder(tok, wid, name):
    """The id of a top-level workspace folder, creating it if absent.

    Returns None when folders are unavailable (an older tenant, or a principal without the
    permission) — the deploy still works and the items land at the workspace root, which is
    where they went before folders existed. A tidier workspace is not worth failing a deploy
    that would otherwise have succeeded.

    Matched case-insensitively: these folders are usually made by hand first, and a second
    'notebooks' beside someone's existing 'Notebooks' splits their organisation rather than
    joining it.
    """
    try:
        r = requests.get(f"{FAB_API}/workspaces/{wid}/folders", headers=_hdr(tok))
        if r.ok:
            for f in r.json().get("value", []):
                if str(f.get("displayName", "")).strip().lower() == name.strip().lower():
                    return f["id"]
        c = requests.post(f"{FAB_API}/workspaces/{wid}/folders", headers=_hdr(tok),
                          json={"displayName": name})
        if c.status_code in (200, 201):
            print(f"  created folder '{name}'")
            return c.json()["id"]
        print(f"  could not create folder '{name}' ({c.status_code}); items go to the root")
    except Exception as e:
        print(f"  folders unavailable ({e}); items go to the root")
    return None


def _renamed_platform(platform, display_name):
    """The item's .platform with its display name matching what we create it as."""
    if not platform:
        return None
    doc = json.loads(platform.decode("utf-8"))
    doc.setdefault("metadata", {})["displayName"] = display_name
    return (json.dumps(doc, indent=2, ensure_ascii=False) + "\n").encode("utf-8")


def _parts(files):
    return [{"path": path, "payload": base64.b64encode(data).decode(),
             "payloadType": "InlineBase64"}
            for path, data in files if data is not None]


def _attach_lakehouse(source, wid, lid):
    """Bind a notebook-content.py to its default lakehouse, in the leading # META block.

    The bundle deliberately omits this: a lakehouse GUID is per-workspace, and a bundle in a
    repo has no workspace. Deploy time is where it becomes knowable. Without it the notebooks
    import and then fail on the first table read with no default lakehouse.
    """
    text = source.decode("utf-8")
    marker = "# METADATA ********************"
    if marker not in text:
        return source
    head, _, rest = text.partition(marker)
    lines = rest.split("\n")
    meta_lines, consumed = [], len(lines)
    for i, line in enumerate(lines):
        if line.startswith("# META "):
            meta_lines.append(line[len("# META "):])
        elif line == "# META":
            meta_lines.append("")
        elif not line.strip() and not meta_lines:
            continue
        else:
            consumed = i
            break
    try:
        meta = json.loads("\n".join(meta_lines))
    except ValueError:
        return source
    meta["dependencies"] = {"lakehouse": {
        "default_lakehouse": lid, "default_lakehouse_workspace_id": wid}}
    rebuilt = [marker, ""]
    for ln in json.dumps(meta, indent=2, ensure_ascii=False).split("\n"):
        rebuilt.append(f"# META {ln}" if ln else "# META")
    return (head + "\n".join(rebuilt + lines[consumed:])).encode("utf-8")


def _create_or_update(tok, wid, collection, name, definition, folder_id=None):
    """Put one item in the workspace, matched BY DISPLAY NAME so a re-run updates it."""
    kind = "notebook" if collection == "notebooks" else "data pipeline"
    r = requests.get(f"{FAB_API}/workspaces/{wid}/{collection}", headers=_hdr(tok))
    if not r.ok:
        raise RuntimeError(
            f"Could not list the workspace's {collection} ({r.status_code}), so an existing "
            "item cannot be told from a missing one."
        )
    existing = next((i for i in r.json().get("value", []) if i.get("displayName") == name), None)
    if existing:
        _poll_lro(requests.post(
            f"{FAB_API}/workspaces/{wid}/{collection}/{existing['id']}/updateDefinition",
            headers=_hdr(tok), json={"definition": definition}), tok)
        print(f"  updated {kind} '{name}'")
        return existing["id"]
    body = {"displayName": name, "definition": definition}
    if folder_id:
        body["folderId"] = folder_id
    res = _poll_lro(requests.post(f"{FAB_API}/workspaces/{wid}/{collection}", headers=_hdr(tok),
                    json=body), tok)
    print(f"  imported {kind} '{name}'" if kind == "notebook" else f"  created {kind} '{name}'")
    return res.get("id")


def import_notebook(tok, wid, name, content, platform, lid, folder_id=None):
    """Import one notebook item folder (idempotent), attaching the lakehouse as its default."""
    return _create_or_update(tok, wid, "notebooks", name, {"parts": _parts([
        ("notebook-content.py", _attach_lakehouse(content, wid, lid)),
        (".platform", _renamed_platform(platform, name)),
    ])}, folder_id)


def _resolve_references(obj, item_ids, wid):
    """Rewrite the bundle's logicalId references to the GUIDs the items actually became.

    A git-layout pipeline names a notebook or a sibling pipeline by that item's logicalId,
    against a zero workspaceId. Fabric's git sync resolves those on "Update all"; the REST
    API does not, so it happens here.

    Only notebookId/pipelineId are looked up and only a ZERO workspaceId is filled in — a
    blanket string replace would also rewrite externalReferences.connection, where the same
    zero GUID means "no connection". An id that is not in the map is left ALONE rather than
    blanked, so the import fails loudly instead of storing a reference to nothing.
    """
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k in ("notebookId", "pipelineId") and isinstance(v, str):
                out[k] = item_ids.get(v, v)
            elif k == "workspaceId" and v == ZERO_GUID:
                out[k] = wid
            else:
                out[k] = _resolve_references(v, item_ids, wid)
        return out
    if isinstance(obj, list):
        return [_resolve_references(v, item_ids, wid) for v in obj]
    return obj


def _unresolved(obj, known):
    """Ids this definition points at that no item accounts for — what makes it unsendable."""
    found = []
    if isinstance(obj, dict):
        for k, v in obj.items():
            if k in ("notebookId", "pipelineId") and isinstance(v, str) and v not in known:
                found.append(v)
            else:
                found += _unresolved(v, known)
    elif isinstance(obj, list):
        for v in obj:
            found += _unresolved(v, known)
    return found


def _set_invoke_connection(obj, conn):
    """Give every Invoke-Pipeline activity the connection, or drop the placeholder.

    The bundle writes a zero GUID where a connection belongs, because a connection is a
    per-tenant object it cannot know. Fabric does NOT read that as "none" — it reads it as a
    connection and refuses the whole pipeline with "User does not have access to the
    connection used in the Pipeline". So either a real one is substituted, or the block goes
    and the invoke runs as the deploying identity.
    """
    if isinstance(obj, dict):
        out = {}
        for k, v in obj.items():
            if k == "externalReferences" and isinstance(v, dict) and v.get("connection") == ZERO_GUID:
                if conn:
                    out[k] = {**v, "connection": conn}
                continue
            out[k] = _set_invoke_connection(v, conn)
        return out
    if isinstance(obj, list):
        return [_set_invoke_connection(v, conn) for v in obj]
    return obj


def create_or_update_pipeline(tok, wid, name, definition, platform=None, folder_id=None):
    return _create_or_update(tok, wid, "dataPipelines", name, {"parts": _parts([
        ("pipeline-content.json", json.dumps(definition).encode("utf-8")),
        (".platform", _renamed_platform(platform, name)),
    ])}, folder_id)


def _strip_generated_header(definition):
    """Drop the __generated_by provenance block before shipping the def to Fabric.

    Belt and braces: the git renderer already strips it, so this only matters for a
    hand-edited pipeline-content.json. It is governance metadata about the FILE.
    """
    return {k: v for k, v in definition.items() if k != "__generated_by"}


def _load_pipelines(domain_filter):
    """Every pipelines/<name>.DataPipeline/ item folder, filtered to one system if asked."""
    out = []
    for base, logical, content, platform, display in _item_folders(
        "pipelines", ".DataPipeline", "pipeline-content.json"
    ):
        if domain_filter and base != domain_filter.replace("/", "_"):
            continue
        definition = _strip_generated_header(json.loads(content.decode("utf-8")))
        out.append((base, logical, definition, platform, display))
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--workspace", required=True, help="Fabric workspace display name")
    ap.add_argument("--lakehouse", required=True, help="schema-enabled lakehouse name")
    ap.add_argument("--capacity", default="", help="Fabric capacity GUID (to create the workspace)")
    ap.add_argument("--setup-only", action="store_true",
                    help="provision + upload + import notebooks; do NOT build pipelines")
    ap.add_argument("--skip-upload", action="store_true", help="contracts already staged in OneLake")
    ap.add_argument("--domain", default="", help="only build one <domain>/<system> pipeline")
    ap.add_argument("--invoke-connection", default="",
                    help="Fabric connection GUID for Invoke-Pipeline activities. Optional: "
                         "without it the placeholder is dropped and invokes run as you")
    args = ap.parse_args()

    fab_tok = _token("https://api.fabric.microsoft.com")
    store_tok = _token("https://storage.azure.com")

    print("-- Provision --------------------------------------------------")
    wid = get_or_create_workspace(fab_tok, args.workspace, args.capacity)
    lid = get_or_create_lakehouse(fab_tok, wid, args.lakehouse)

    if args.skip_upload:
        print("-- Upload contracts -- skipped --------------------------------")
    else:
        print("-- Upload contracts -------------------------------------------")
        upload_contracts(store_tok, args.workspace, args.lakehouse)

    print("-- Import notebooks -------------------------------------------")
    notebooks = _item_folders("notebooks", ".Notebook", "notebook-content.py")
    if not notebooks:
        sys.exit(
            "No notebooks/<name>.Notebook item folders in this bundle, so there is nothing "
            "to import. Deploying the pipelines alone would create items pointing at "
            "notebooks that do not exist."
        )
    # logicalId -> the GUID it became. Notebooks and pipelines share one map, because a
    # reference names an ITEM, not a kind.
    item_ids = {}
    # The workspace folders, named by the bundle's own directories — the same names Fabric's
    # git integration derives from those directories when the SAME bundle is synced from a
    # repo, so both routes put the items in the same place.
    nb_folder = ensure_folder(fab_tok, wid, _item_dir("notebooks").name)
    for base, logical, content, platform, display in notebooks:
        item_id = import_notebook(fab_tok, wid, display or base, content, platform, lid,
                                  nb_folder)
        if logical:
            item_ids[logical] = item_id

    if args.setup_only:
        print("Setup-only complete.")
        return

    print("-- Data Pipelines ---------------------------------------------")
    pipelines = _load_pipelines(args.domain)
    definitions = {
        base: _set_invoke_connection(definition, args.invoke_connection)
        for base, _logical, definition, _platform, _display in pipelines
    }
    # The bundle names its own items — the convention needs the environment, domain and
    # system, which a file stem cannot be parsed back into. The stem is the fallback.
    names = {base: (display or base) for base, _l, _d, _p, display in pipelines}
    pl_folder = ensure_folder(fab_tok, wid, _item_dir("pipelines").name)

    # Created in DEPENDENCY order, not name order: the mesh orchestrator invokes the
    # per-system pipelines, and sent first its pipelineId names an item that does not exist
    # yet — which Fabric answers with a 400 that says nothing. Rounds rather than a sort, so
    # a chain of any depth works without modelling it.
    pending = list(pipelines)
    while pending:
        ready = [row for row in pending if not _unresolved(definitions[row[0]], item_ids)]
        if not ready:
            break
        for row in ready:
            base, logical, _definition, platform, _display = row
            pipeline_id = create_or_update_pipeline(
                fab_tok, wid, names[base],
                _resolve_references(definitions[base], item_ids, wid), platform, pl_folder)
            if logical:
                item_ids[logical] = pipeline_id
            pending.remove(row)

    # Anything left references something no round could supply: a cycle between pipelines, or
    # an id no item accounts for. A cycle is legitimate and unorderable, so those are created
    # EMPTY first — which gives every logicalId a GUID — and then given their definitions.
    for base, logical, _definition, platform, _display in pending:
        pipeline_id = _create_or_update(
            fab_tok, wid, "dataPipelines", names[base],
            {"parts": _parts([(".platform", _renamed_platform(platform, names[base]))])},
            pl_folder)
        if logical:
            item_ids[logical] = pipeline_id
    for base, _logical, _definition, platform, _display in pending:
        create_or_update_pipeline(
            fab_tok, wid, names[base],
            _resolve_references(definitions[base], item_ids, wid), platform, pl_folder)

    dangling = sorted({ref for base in definitions for ref in _unresolved(definitions[base], item_ids)})
    if dangling:
        print(f"  WARNING: {len(dangling)} reference(s) name no item in this bundle and were "
              "left as they are.")
    if not args.invoke_connection and any(
        "InvokePipeline" in json.dumps(d) for d in definitions.values()
    ):
        print("  note: no --invoke-connection given, so pipeline invokes run as you. Pass a "
              "connection GUID to change that.")

    print("Deploy complete. Run the per-system pipelines (or the mesh orchestrator) in Fabric.")


if __name__ == "__main__":
    main()
