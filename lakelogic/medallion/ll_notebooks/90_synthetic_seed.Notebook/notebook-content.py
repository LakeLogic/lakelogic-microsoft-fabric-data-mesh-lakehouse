"""LakeLogic synthetic-bronze seed — ONE neutral runner, shipped verbatim into every rendered
Medallion project and wrapped thinly per engine.

The deliverable is a **synthetic replica of the org's application estate**: for every *bronze*
contract in a system's registry it generates contract-derived rows and writes them as a
**Delta table directly in the lake** (Parquet on engines that aren't Delta-native). That synthetic
bronze is valuable on its own — safe (zero production rows read), governed (same contracts), and
FK-consistent — so an org can use it for development, testing, demos and CI without touching real
data. Running the medallion pipeline (silver→gold) on top is optional.

Library-first: the generation is entirely the OSS ``lakelogic`` engine —
:meth:`lakelogic.core.generator.DataGenerator.generate_related`, which auto-detects PK/FK
relationships across the bronze contracts and generates parents before children so foreign keys
contain valid references (a single per-table ``generate()`` loop would not). This module only
orchestrates: read registry → generate_related → write each frame to the lake.

Engine-agnostic by construction: generation returns Polars frames and the write is Polars'
``write_delta`` / ``write_parquet`` — no Spark, Fabric, Databricks or Snowflake dependency. The
ONLY per-engine variance is ``out_root`` (where the lake is mounted) and, for a non-Delta engine,
``fmt="parquet"``. A thin engine wrapper (a Fabric notebook cell, a Databricks task, a Snowpark
notebook) calls :func:`seed_bronze_estate` (or runs this file's ``main``) with those two values.

Determinism: same ``seed`` + fixed generation ``window`` → byte-reproducible rows. Every synthetic
row carries a permanent ``_synthetic=True`` marker column so a twin is self-identifying downstream
and can never be mistaken for production.

This file is SELF-CONTAINED (only stdlib + ``lakelogic`` + ``polars``) so it ships verbatim and runs
on the customer's compute. It contains NO ``api.*`` imports — do not add any. (No
``from __future__ import annotations`` on purpose: this source is embedded verbatim into a Fabric
notebook cell alongside other cells, and a future-import is only valid at the top of a compilation
unit — the standard ``Optional``/``List``/``Dict`` hints evaluate fine without it.)
"""
import argparse
import os
from datetime import datetime
from typing import Any, Dict, List, Optional

# A fixed generation window pins temporal columns so the twin is reproducible from the seed.
_DEFAULT_WINDOW_START = datetime(2020, 1, 1)
_DEFAULT_WINDOW_END = datetime(2025, 1, 1)
_MARKER = "_synthetic"


def _fields_of(contract_dict: Dict[str, Any]) -> List[str]:
    """Column names declared on a contract's schema (``model.fields[].name``)."""
    model = contract_dict.get("model") if isinstance(contract_dict, dict) else None
    fields = (model or {}).get("fields") or []
    return [f.get("name") for f in fields if isinstance(f, dict) and f.get("name")]


def _infer_relationships(entity_columns: Dict[str, List[str]]) -> List[Dict[str, str]]:
    """Derive FK edges from column naming so ``generate_related`` injects valid references.

    Bronze contracts are raw and declare no primary key, so ``generate_related`` can order tables
    but can't wire a child's FK to a parent's PK pool on its own. We supply the edges: a column
    ``<base>_id`` on a child entity references the parent entity that *owns* that key — i.e. an
    entity whose own name matches ``<base>`` (singular or plural) and which carries the same
    ``<base>_id`` column. Deterministic (sorted); unmatched ``*_id`` columns are left alone (they
    become ordinary fake ids, which is correct when there's no in-estate parent).
    """
    # Which entity owns each ``<name>_id`` key column (the parent whose own name is <name>).
    owner_of: Dict[str, str] = {}
    for ent in sorted(entity_columns):
        singular = ent[:-1] if ent.endswith("s") else ent
        for cand in (f"{ent}_id", f"{singular}_id"):
            if cand in entity_columns[ent]:
                owner_of.setdefault(cand, ent)
    rels: List[Dict[str, str]] = []
    seen = set()
    for child in sorted(entity_columns):
        for col in entity_columns[child]:
            if not (isinstance(col, str) and col.endswith("_id")):
                continue
            parent = owner_of.get(col)
            if parent and parent != child and (child, col) not in seen:
                seen.add((child, col))
                rels.append({"child": child, "child_column": col,
                             "parent": parent, "parent_column": col})
    return rels


def generate_bronze_frames(
    registry_path: str,
    *,
    environment: str = "dev",
    storage_mode: str = "catalog",
    rows: int = 200,
    seed: int = 7,
    invalid_ratio: float = 0.0,
    window_start: Optional[datetime] = None,
    window_end: Optional[datetime] = None,
    generative: bool = False,
    ai_provider: Optional[str] = None,
    ai_model: Optional[str] = None,
) -> Dict[str, Any]:
    """The shared, engine-agnostic GENERATION step: a FK-consistent synthetic bronze estate as
    ``{entity: polars.DataFrame}``, each frame stamped ``_synthetic=True``. NO write.

    Reads the *schema only* of every bronze contract in ``registry_path`` (never a production row),
    infers FK edges from column naming, and generates referentially-consistent rows via
    ``DataGenerator.generate_related``. Every engine wrapper calls this; the WRITE is engine-specific
    (Delta path on Fabric, ``spark.saveAsTable`` on Databricks, Parquet→stage on Snowflake). Raises
    ``RuntimeError`` if the system has no bronze contracts.
    """
    from lakelogic.core.generator import DataGenerator
    from lakelogic.core.registry import DomainRegistry
    import polars as pl

    rows = max(1, int(rows))
    window_start = window_start or _DEFAULT_WINDOW_START
    window_end = window_end or _DEFAULT_WINDOW_END

    registry = DomainRegistry.from_yaml(
        registry_path, environment=environment, storage_mode=storage_mode
    )
    # Bronze contracts only — the raw twin. generate_related keys on the entity name; using the
    # resolved contract YAML path as the source lets it read each schema (+ PII/masking metadata).
    bronze_contracts = [
        c for c in registry.contracts if c.layer == "bronze" and c.resolved_path
    ]
    if not bronze_contracts:
        raise RuntimeError(
            f"No bronze contracts in {registry_path} — nothing to seed."
        )
    bronze = {c.entity: c.resolved_path for c in bronze_contracts}
    # Infer FK edges from the contract schemas so foreign keys reference real parent rows.
    entity_columns = {c.entity: _fields_of(c.contract_dict or {}) for c in bronze_contracts}
    relationships = _infer_relationships(entity_columns)

    def _generate(ai_on: bool) -> Dict[str, Any]:
        kwargs: Dict[str, Any] = dict(
            rows=rows, invalid_ratio=invalid_ratio, seed=seed, output_format="polars",
            window_start=window_start, window_end=window_end,
            relationships=relationships or None,
        )
        if ai_on:
            kwargs.update(ai=True, ai_provider=ai_provider, ai_model=ai_model)
        return DataGenerator.generate_related(bronze, **kwargs)

    # Deterministic by default. The generative tier (realistic, domain-appropriate values via the
    # OSS AI generator) is capability-gated on an LLM provider being configured in the RUNTIME's
    # environment (OPENAI_API_KEY / ANTHROPIC_API_KEY / … or LAKELOGIC_AI_PROVIDER) — the customer's
    # compute, which LakeLogic never runs. If it's requested but unavailable, fall back to the
    # deterministic estate with a warning rather than failing the seed (matches the Builder's
    # AI-fallback posture); a genuine (non-AI) generation error still propagates from the fallback.
    if generative:
        try:
            frames = _generate(True)
        except Exception as exc:  # noqa: BLE001 — provider/credential/AI failure → degrade, don't fail
            print(
                f"[synthetic_seed] generative mode unavailable ({type(exc).__name__}: {exc}); "
                "falling back to deterministic generation. Configure an LLM provider "
                "(e.g. OPENAI_API_KEY) in this environment to enable it."
            )
            frames = _generate(False)
    else:
        frames = _generate(False)

    out: Dict[str, Any] = {}
    for entity in sorted(frames):  # deterministic order
        df = frames[entity]
        # Drop the generator's internal bookkeeping column; stamp the permanent synthetic marker.
        if "_is_invalid" in df.columns:
            df = df.drop("_is_invalid")
        out[entity] = df.with_columns(pl.lit(True).alias(_MARKER))
    return out


def seed_bronze_estate(
    registry_path: str,
    out_root: str,
    *,
    environment: str = "dev",
    storage_mode: str = "catalog",
    rows: int = 200,
    seed: int = 7,
    invalid_ratio: float = 0.0,
    window_start: Optional[datetime] = None,
    window_end: Optional[datetime] = None,
    fmt: str = "delta",
    write_mode: str = "overwrite",
    generative: bool = False,
    ai_provider: Optional[str] = None,
    ai_model: Optional[str] = None,
) -> List[Dict[str, Any]]:
    """Generate a synthetic bronze estate (:func:`generate_bronze_frames`) and WRITE it under
    ``out_root`` as Delta (``fmt="delta"``) or Parquet (``fmt="parquet"``) files — the path-based
    write used by Fabric (OneLake ``Tables/``) and local runs. Databricks/Snowflake wrappers call
    :func:`generate_bronze_frames` and write via their native table API instead.

    Returns a per-entity report (``[{entity, rows, path, format}]``).
    """
    fmt = (fmt or "delta").strip().lower()
    if fmt not in ("delta", "parquet"):
        raise ValueError(f"fmt must be 'delta' or 'parquet', got {fmt!r}")

    frames = generate_bronze_frames(
        registry_path, environment=environment, storage_mode=storage_mode, rows=rows, seed=seed,
        invalid_ratio=invalid_ratio, window_start=window_start, window_end=window_end,
        generative=generative, ai_provider=ai_provider, ai_model=ai_model,
    )
    report: List[Dict[str, Any]] = []
    for entity, df in frames.items():
        dest = f"{out_root.rstrip('/')}/{entity}"
        if fmt == "delta":
            df.write_delta(dest, mode=write_mode)
        else:
            # A directory-per-table Parquet layout (external-table / stage friendly).
            os.makedirs(dest, exist_ok=True)
            df.write_parquet(f"{dest}/{entity}.parquet")
        report.append({"entity": entity, "rows": df.height, "path": dest, "format": fmt})
    return report


def main(argv: Optional[List[str]] = None) -> int:
    """Script entry-point so a thin engine wrapper can just run this file. Params come from CLI
    flags or the matching ``SYNTH_*`` env vars (whichever a platform's task runner makes easy)."""
    p = argparse.ArgumentParser(description="Write a synthetic bronze estate to the lake.")
    p.add_argument("--registry", default=os.getenv("SYNTH_REGISTRY_PATH"),
                   help="Path to the system's _system.yaml registry.")
    p.add_argument("--out-root", default=os.getenv("SYNTH_OUT_ROOT"),
                   help="Lake root the synthetic bronze tables are written under.")
    p.add_argument("--rows", type=int, default=int(os.getenv("SYNTH_ROWS", "200")))
    p.add_argument("--seed", type=int, default=int(os.getenv("SYNTH_SEED", "7")))
    p.add_argument("--invalid-ratio", type=float, default=float(os.getenv("SYNTH_INVALID_RATIO", "0.0")))
    p.add_argument("--environment", default=os.getenv("SYNTH_ENVIRONMENT", "dev"))
    p.add_argument("--fmt", default=os.getenv("SYNTH_FORMAT", "delta"), choices=["delta", "parquet"])
    p.add_argument("--generative", action="store_true",
                   default=os.getenv("SYNTH_GENERATIVE", "").strip().lower() in ("1", "true", "yes"),
                   help="Enable AI-enriched realistic values (needs an LLM key in this env).")
    p.add_argument("--ai-provider", default=os.getenv("SYNTH_AI_PROVIDER") or os.getenv("LAKELOGIC_AI_PROVIDER"))
    p.add_argument("--ai-model", default=os.getenv("SYNTH_AI_MODEL") or os.getenv("LAKELOGIC_AI_MODEL"))
    args = p.parse_args(argv)

    if not args.registry or not args.out_root:
        p.error("--registry and --out-root (or SYNTH_REGISTRY_PATH / SYNTH_OUT_ROOT) are required")

    report = seed_bronze_estate(
        args.registry, args.out_root,
        environment=args.environment, rows=args.rows, seed=args.seed,
        invalid_ratio=args.invalid_ratio, fmt=args.fmt,
        generative=args.generative, ai_provider=args.ai_provider, ai_model=args.ai_model,
    )
    total = sum(r["rows"] for r in report)
    for r in report:
        print(f"  {r['entity']}: {r['rows']} rows -> {r['path']} ({r['format']})")
    print(f"Synthetic bronze estate: {len(report)} table(s), {total} rows.")
    return 0

